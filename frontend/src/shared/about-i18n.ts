export type AboutLanguage = 'zh-CN' | 'en-US';
export type AboutTranslation = keyof typeof zh;

export async function createAboutI18n() {
  const instance = i18next.createInstance();
  await instance.init({
    lng: 'zh-CN',
    fallbackLng: 'en-US',
    defaultNS: 'about',
    resources: { 'zh-CN': { about: zh }, 'en-US': { about: en } },
    interpolation: { escapeValue: false }
  });
  return instance;
}
