"use strict";
const assert = require("node:assert/strict");
const {loadFrontendService} = require("./frontend-service-test-helper");
const {freshPanelLayout, cleanPanelLayout, cleanPanelPreferences, createPanelModel, panelLayout} =
  loadFrontendService("frontend/src/features/terminal-panel/panel-model.ts", {window:{}});
const plain = value => JSON.parse(JSON.stringify(value));

const original = freshPanelLayout(["commands", "files"]);
original.password = "must-not-persist";
original.tabs[0].command = "must-not-run";
original.tabs[0].binding = {mode:"connection", connectionId:7, token:"must-not-persist"};
original.height = Infinity;
original.width = -1;
const cleaned = cleanPanelLayout(original);
assert.equal(cleaned.height, 220);
assert.equal(cleaned.width, 260);
assert.equal(cleaned.tabs[0].binding, undefined, "legacy binding is removed; all tools follow main terminal");
assert.doesNotMatch(JSON.stringify(cleaned), /must-not|password|command"|token/);
const duplicated = freshPanelLayout(["commands", "files"]);
duplicated.tabs.push({...duplicated.tabs[0]});
duplicated.tabs.push({key:"panel-tab-duplicate-files",kind:"files"});
duplicated.layout.tabs.push("missing", duplicated.tabs[0].key, "panel-tab-duplicate-files");
duplicated.rightLayout={type:"pane",id:duplicated.layout.id,tabs:[duplicated.tabs[0].key],activeTabKey:duplicated.tabs[0].key};
const restored = cleanPanelLayout(duplicated);
assert.equal(restored.tabs.length, 4);
assert.equal(new Set(panelLayout.leaves(restored.layout).flatMap(pane => pane.tabs)).size, 4);
assert.equal(restored.rightLayout, null);

const cycle = {type:"split", id:"cycle", direction:"row", ratio:0.5};
cycle.first = cycle; cycle.second = original.layout;
assert.doesNotThrow(() => cleanPanelLayout({...original, layout:cycle}));
assert.deepEqual(plain(cleanPanelLayout({version:99})), plain(freshPanelLayout()));
const migrated = cleanPanelPreferences(null, {visible:"1", height:"76"});
assert.equal(migrated.visible, true);
assert.equal(migrated.current.height, 140);
let changes = 0;
const model = createPanelModel(migrated, () => changes++);
const added = model.add("files", "column");
assert.ok(added.startsWith("panel-tab-"));
assert.equal(panelLayout.leaves(model.current().layout).length, 2);
model.state.presetDraft = "Review layout";
const id = model.savePreset();
assert.ok(id);
model.state.preferences.defaultId = id;
model.current().height = 300;
assert.notEqual(model.state.preferences.presets[0].value.height, 300, "saved layouts must be snapshots");
model.state.presetDraft = "Renamed layout";
model.renamePreset(id);
assert.equal(model.state.preferences.presets[0].name, "Renamed layout");
model.restore(model.state.preferences.presets[0].value);
assert.equal(model.current().height, 140);
assert.equal(model.current().tabs[1].binding, undefined);
const first = model.current().tabs[0].key, firstPane = panelLayout.findPaneForTab(first,model.current().layout);
assert.equal(model.move(added,{paneId:firstPane.id,zone:"center"}),true);
assert.equal(panelLayout.leaves(model.current().layout).length,1);
assert.equal(model.move(added,{paneId:firstPane.id,zone:"bottom"}),true);
assert.equal(panelLayout.leaves(model.current().layout).length,2);
assert.equal(new Set(panelLayout.leaves(model.current().layout).flatMap(p=>p.tabs)).size,4);
assert.equal(cleanPanelLayout({...model.current(),height:0}).height,28);
assert.equal(model.dock(added, "right"), true);
assert.equal(model.findPaneForTab(added).id, model.current().rightLayout.id);
assert.equal(model.current().layout.tabs.includes(added), false);
model.toggleSection(model.current().rightLayout.id, added);
assert.ok(model.state.collapsedRight.has(added));
model.activate(model.current().rightLayout.id, added);
assert.equal(model.state.collapsedRight.has(added), false);
model.toggleSection(model.current().rightLayout.id, added);
model.toggleSection(model.current().rightLayout.id, added);
assert.equal(model.state.collapsedRight.has(added), false);
assert.equal(model.close(added), true);
assert.equal(model.current().rightLayout, null);
assert.ok(model.findPaneForTab(added).tabs.includes(added));
assert.equal(model.current().tabs.length, 4);
assert.equal(model.close(model.current().tabs[0].key), false);
for (let index = 0; index < 20; index++) model.add("commands");
assert.equal(model.current().tabs.length, 4);
const keys = model.current().tabs.map(tab=>tab.key);
model.restore(freshPanelLayout(["terminal"]));
assert.deepEqual([...model.current().tabs.map(tab=>tab.key)].sort(), [...keys].sort(), "presets preserve controller identities");
model.dock(added,"right");
const bottom = model.current().layout.id;
assert.equal(model.move(added,{paneId:bottom,zone:"left"}),true);
assert.equal(model.current().rightLayout,null);
assert.equal(panelLayout.leaves(model.current().layout).length,2);
for (const tab of model.current().tabs) model.dock(tab.key,"right");
assert.equal(model.current().layout,null);
model.state.maximized=true;model.state.maximizedRegion="right";
model.returnRight();
assert.equal(model.current().rightLayout,null);
assert.equal(model.state.maximized,false);
assert.equal(new Set(model.leaves().flatMap(p=>p.tabs)).size,4);
const legacy = {version:1,position:"right",tabs:[{key:"panel-tab-old",kind:"terminal"}],
  layout:{type:"pane",id:"old",tabs:["panel-tab-old"],activeTabKey:"panel-tab-old"}};
const upgraded = cleanPanelLayout(legacy);
assert.equal(upgraded.rightLayout.activeTabKey,"panel-tab-old");
assert.equal(upgraded.tabs.length,4);
assert.equal(panelLayout.leaves(upgraded.layout)[0].tabs.length,3);
model.deletePreset(id);
assert.equal(model.state.preferences.defaultId, "");
assert.ok(changes > 10);
const {createLocalTerminalGroups} = loadFrontendService("frontend/src/features/terminal-panel/panel-terminal-model.ts");
const groups = createLocalTerminalGroups();
groups.add("one"); groups.add("two"); groups.add("three", "row");
assert.equal(groups.groups.length, 2);
assert.deepEqual(plain(groups.keys(groups.current().layout)), ["two","three"]);
groups.select("one"); groups.add("four","column");
assert.equal(groups.current().layout.direction,"column");
groups.select("missing"); assert.equal(groups.focused,"four");
groups.remove("four"); assert.equal(groups.focused,"one");
assert.equal(groups.current().layout.type,"pane");
groups.remove("one"); assert.equal(groups.focused,"two");
groups.remove("two"); assert.equal(groups.focused,"three");
groups.remove("three"); assert.equal(groups.current(),undefined); assert.equal(groups.focused,"");
const {createFileListWindow} = loadFrontendService("frontend/src/features/files/file-list-window.ts");
const window = createFileListWindow();
const fill = page => Array.from({length:50},(_,i)=>({index:(page-1)*50+i}));
window.sync("host/path",1,50,50000,fill(1));
assert.equal(window.range(0,400,36).missingPage,0);
assert.ok(window.range(0,400,36).items.length<40);
assert.equal(window.range(25000*36,400,36).missingPage,500,"overscan requests the preceding page");
for(let page=495;page<=510;page++){window.sync("host/path",page,50,50000,fill(page));window.range(25000*36,400,36);}
assert.ok(window.pageCount()<=5,"cache stays bounded when jumping through a large directory");
window.sync("host/path",1000,50,50000,fill(1000));
const end = window.range(50000*36,400,36);
assert.equal(end.items.at(-1).value.index,49999);assert.equal(end.bottom,0);
window.sync("other-host/path",1,50,1,[{index:0}]);
assert.equal(window.loaded().length,1,"changing ownership clears every cached page");
console.log("Utility panel checks passed: four singleton tools, dual docks, return/split, legacy migration, stable identities and secret whitelist.");
